// Helper to support canonical IDs or aliases (e.g. 'fire' -> 'fireplace', 'brown' -> 'brown-noise')
export const getSoundById = (id: string): SoundTrack | undefined => {
  const normalizedId = normalizeSoundId(id);
  return SOUND_TRACKS.find((s) => s.id === normalizedId || s.id === id);
};

export const normalizeSoundId = (id: string): string => {
  switch (id) {
    case 'fireplace':
      return 'fire';
    case 'wind':
      return 'breeze';
    case 'night':
      return 'meadow';
    case 'zen-bowls':
      return 'bowls';
    case 'brown-noise':
      return 'brown';
    default:
      return id;
  }
};
